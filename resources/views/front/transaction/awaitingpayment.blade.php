            document.addEventListener("DOMContentLoaded", function () {
        // Ambil data tanggal order dari backend, jika tidak ada gunakan waktu saat ini + 1 hari sebagai fallback
        const orderCreatedAtStr = "{{ $order->created_at ?? '' }}";
        
        let countDownDate;
        if (orderCreatedAtStr) {
            // Tambahkan 24 jam (1 hari) dari waktu order dibuat
            countDownDate = new Date(orderCreatedAtStr).getTime() + (24 * 60 * 60 * 1000);
        } else {
            // Jika kosong, buat countdown default 24 jam dari sekarang agar tidak eror
            countDownDate = new Date().getTime() + (24 * 60 * 60 * 1000);
        }

        // Cari elemen tempat menampilkan timer
        const timerElement = document.getElementById("countdown-timer");

        // Jalankan timer hanya jika elemennya ada di halaman
        if (timerElement) {
            const x = setInterval(function() {
                const now = new Date().getTime();
                const distance = countDownDate - now;

                // Hitung jam, menit, dan detik
                const hours = Math.floor((distance % (1000 * 60 * 60 * 24)) / (1000 * 60 * 60));
                const minutes = Math.floor((distance % (1000 * 60 * 60)) / (1000 * 60));
                const seconds = Math.floor((distance % (1000 * 60)) / 1000);

                // Tampilkan hasil ke dalam elemen dengan format 00:00:00
                timerElement.innerHTML = 
                    (hours < 10 ? "0" : "") + hours + ":" + 
                    (minutes < 10 ? "0" : "") + minutes + ":" + 
                    (seconds < 10 ? "0" : "") + seconds;

                // Jika hitung mundur selesai
                if (distance < 0) {
                    clearInterval(x);
                    timerElement.innerHTML = "EXPIRED";
                }
            }, 1000);
        }
    });

